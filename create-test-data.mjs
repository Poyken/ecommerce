// Update SKU prices and stock
async function updateSkuPricing() {
  console.log('\n💰 Updating SKU prices and stock...');
  
  try {
    // Get all SKUs
    const result = await apiRequest('/skus?limit=100');
    const skus = result.data?.items || [];
    
    console.log(`  Found ${skus.length} SKUs to update`);
    
    // Define price ranges by product name patterns
    const priceMap = {
      'headphones': { min: 2500000, max: 3500000 },
      'watch': { min: 5000000, max: 7000000 },
      't-shirt': { min: 250000, max: 400000 },
      'jeans': { min: 800000, max: 1000000 },
      'lamp': { min: 700000, max: 900000 },
      'pot': { min: 400000, max: 800000 }
    };
    
    let updated = 0;
    for (const sku of skus) {
      try {
        // Determine price based on product name
        let price = 500000; // default
        const skuCode = sku.skuCode?.toLowerCase() || '';
        
        for (const [key, range] of Object.entries(priceMap)) {
          if (skuCode.includes(key)) {
            price = Math.floor(Math.random() * (range.max - range.min + 1)) + range.min;
            break;
          }
        }
        
        // Random stock between 20-100
        const stock = Math.floor(Math.random() * 81) + 20;
        
        // Image URL from Unsplash
        const imageUrl = 'https://images.unsplash.com/photo-1523275335684-37898b6baf30?w=500&q=80';
        
        await apiRequest(`/skus/${sku.id}`, 'PATCH', {
          price,
          stock,
          imageUrl,
          status: 'ACTIVE'
        });
        
        updated++;
      } catch (error) {
        console.error(`    ❌ Failed to update SKU ${sku.skuCode}:`, error.message.substring(0, 100));
      }
    }
    
    console.log(`  ✅ Updated ${updated}/${skus.length} SKUs`);
  } catch (error) {
    console.error(`  ❌ Failed to update SKU pricing:`, error.message.substring(0, 200));
  }
}

// Main execution

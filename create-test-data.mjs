/**
 * Script to populate e-commerce database with test data
 * Run with: node create-test-data.mjs
 */

const API_URL = 'http://localhost:8080/api/v1';
let accessToken = '';

// Login as admin
async function login() {
  const response = await fetch(`${API_URL}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      email: 'admin@example.com',
      password: '123456'
    })
  });
  
  const data = await response.json();
  if (data.data?.accessToken) {
    accessToken = data.data.accessToken;
    console.log('✅ Logged in as admin');
    return true;
  }
  console.error('❌ Login failed:', data);
  return false;
}

// Helper to make authenticated requests
async function apiRequest(endpoint, method = 'GET', body = null) {
  const options = {
    method,
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${accessToken}`
    }
  };
  
  if (body) {
    options.body = JSON.stringify(body);
  }
  
  const response = await fetch(`${API_URL}${endpoint}`, options);
  const data = await response.json();
  
  if (!response.ok) {
    const errorMsg = JSON.stringify(data, null, 2);
    throw new Error(`API Error ${response.status}: ${errorMsg}`);
  }
  
  return data;
}

// Create categories
async function createCategories() {
  console.log('\n📁 Creating categories...');
  const categories = [
    { name: 'Electronics', slug: 'electronics' },
    { name: 'Clothing', slug: 'clothing' },
    { name: 'Home & Garden', slug: 'home-garden' }
  ];
  
  const createdCategories = [];
  for (const cat of categories) {
    try {
      const result = await apiRequest('/categories', 'POST', cat);
      createdCategories.push(result.data);
      console.log(`  ✅ Created category: ${cat.name} (ID: ${result.data.id})`);
    } catch (error) {
      console.error(`  ❌ Failed to create category ${cat.name}:`, error.message.substring(0, 150));
    }
  }
  return createdCategories;
}

